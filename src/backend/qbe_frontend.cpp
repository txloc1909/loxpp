int runQbeTarget(const std::string& exePath, const std::string& scriptPath,
                 bool noPromote, bool noFuse) {
    std::ifstream file(scriptPath);
    if (!file) {
        std::fprintf(stderr, "loxpp --target qbe: cannot read %s\n",
                     scriptPath.c_str());
        return 74;
    }
    std::stringstream ss;
    ss << file.rdbuf();
    std::string source = ss.str();

    MemoryManager mm;
    ObjFunction* script = compile(source, &mm);
    if (script == nullptr) {
        return 65;
    }

    qbe::EmitOptions options;
    options.promoteRegisters = !noPromote;
    options.fuseTagJumpTable = !noFuse;

    std::string ssa;
    std::vector<CompiledFunction> fns;
    try {
        DecodedFunction tree = decodeFunctionTree(script);
        StackAnalysisTree analysis = analyzeStackTree(tree);
        CaptureAnalysis captures = analyzeCaptures(tree);
        emitTree(tree, analysis, captures, options, ssa, fns);
    } catch (const std::exception& e) {
        std::fprintf(stderr, "loxpp --target qbe: %s\n", e.what());
        return 70;
    }

    std::string libPath;
    const char* envLib = std::getenv("LOX_RT_A");
    if (envLib != nullptr && *envLib != '\0') {
        libPath = envLib;
    } else {
        std::string dir = executableDir();
        if (!dir.empty()) {
            libPath = dir + "/libloxrt.a";
        }
    }
    if (libPath.empty() || !std::filesystem::exists(libPath)) {
        std::fprintf(stderr,
                     "loxpp --target qbe: libloxrt.a not found (set LOX_RT_A "
                     "or place it beside the loxpp binary)\n");
        return 74;
    }

    std::string work = makeTempDir();
    if (work.empty()) {
        std::fprintf(stderr, "loxpp --target qbe: cannot create a temporary "
                             "directory\n");
        return 74;
    }
    struct Cleanup {
        std::string dir;
        ~Cleanup() {
            std::error_code ec;
            std::filesystem::remove_all(dir, ec);
        }
    } cleanup{work};

    std::string ssaPath = work + "/prog.ssa";
    std::string asmPath = work + "/prog.s";
    std::string harnessPath = work + "/harness.cpp";
    if (!writeFile(ssaPath, ssa) ||
        !writeFile(harnessPath, buildHarness(source, fns))) {
        std::fprintf(stderr,
                     "loxpp --target qbe: cannot write files under %s\n",
                     work.c_str());
        return 74;
    }

    std::string qbeBin = resolveTool("QBE", "qbe");
    int rc = runProcess({qbeBin, "-o", asmPath, ssaPath});
    if (rc != 0) {
        if (rc == 127) {
            std::fprintf(stderr,
                         "loxpp --target qbe: '%s' not found (set QBE)\n",
                         qbeBin.c_str());
        } else {
            std::fprintf(stderr, "loxpp --target qbe: qbe failed on %s\n",
                         scriptPath.c_str());
        }
        return 70;
    }

    // Prefer CXX, then c++, then cc. A 127 (not found) advances to the next
    // candidate; any other failure is a real link/compile error and stops.
    std::vector<std::string> compilers;
    const char* envCxx = std::getenv("CXX");
    if (envCxx != nullptr && *envCxx != '\0') {
        compilers.emplace_back(envCxx);
    } else {
        compilers.emplace_back("c++");
        compilers.emplace_back("cc");
    }
    rc = 127;
    for (const std::string& compiler : compilers) {
        rc = runProcess({compiler, "-std=c++17", "-O2", harnessPath, asmPath,
                         libPath, "-lstdc++", "-lm", "-o", exePath});
        if (rc != 127) {
            break;
        }
    }
    if (rc == 127) {
        std::fprintf(stderr,
                     "loxpp --target qbe: no C++ compiler found (set CXX)\n");
        return 70;
    }
    if (rc != 0) {
        std::fprintf(stderr, "loxpp --target qbe: link failed\n");
        return 70;
    }
    return 0;
}
