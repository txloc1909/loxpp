#!/usr/bin/env python3
"""Generate self-timing benchmark programs from the algorithm cores in core/.

Each program in programs/ is  core/<name>.lox  +  a standard harness footer.
The footer runs benchmark() WARM*REPS times to warm the runtime, then times
MEASURE batches of REPS calls each, printing one line per batch:

    HARNESS <batch-index> <microseconds> <checksum>

clock() is process CPU time on the native and CLR backends and wall-clock on
the JVM backend (runtime/jvm/src/lox/LoxRuntime.java). On an unloaded machine
the two agree for a single-threaded steady-state loop; the runner also records
external wall-clock per process as a cross-check.

SIZE_PATCHES scales a benchmark's built-in workload so one REPS batch lands in
the 80-250 ms range on the native backend. WARM is large (25 batches) because
HotSpot tiered compilation keeps improving fasta/json for the first ~10
measured batches otherwise; run.py additionally drops the first third of the
measured batches before taking the median.

richards is the one exception to the 80-250 ms target: its own scheduler
runs a fixed 10000-tick workload tied to a hardcoded self-check, so its
per-call cost (~2s natively) is not reducible without losing that check.
"""
from __future__ import annotations

import re
from pathlib import Path

HERE = Path(__file__).parent
CORE = HERE / "core"
OUT = HERE / "programs"

# name: (benchmark class, warmup batches, measured batches, reps per batch)
CONFIG = {
    "fib":                ("Fib",               25, 12, 1),
    "bounce":             ("Bounce",            25, 12, 30),
    "list":               ("List",              25, 12, 25),
    "mandelbrot":         ("Mandelbrot",        25, 12, 1),
    "nbody":              ("NBody",             25, 12, 1),
    "permute":            ("Permute",           25, 12, 25),
    "queens":             ("Queens",            25, 12, 40),
    "sieve":              ("Sieve",             25, 12, 50),
    "storage":            ("Storage",           25, 12, 8),
    "towers":             ("Towers",            25, 12, 12),
    "json":               ("Json",              25, 12, 8),
    # reps=1: a single call now runs richards's full intended workload
    # (~2s natively) since its scheduler-deadlock bug was fixed — reps=3
    # (tuned for the old, near-instant broken version) would take ~6s/batch.
    # This is well outside the 80-250ms window every other entry targets;
    # accepted as-is rather than shrinking the workload and losing the
    # benchmark's own internal self-check (Scheduler.start()'s assertion is
    # tied to the canonical IDLER count of 10000).
    "richards":           ("Richards",          25, 12, 1),
    "binary_trees":       ("BinaryTrees",       25, 12, 1),
    "spectral_norm":      ("SpectralNorm",      25, 12, 1),
    "fasta":              ("Fasta",             25, 12, 40),
    "k_nucleotide":       ("KNucleotide",       25, 12, 30),
    "reverse_complement": ("ReverseComplement", 25, 12, 30),
    "fannkuch":           ("Fannkuch",          25, 12, 1),
}

# Every name here has the class/benchmark() shape CONFIG expects (checked by
# check_coverage() below) but is deliberately left out of it. Listed here so
# the gap in CONFIG is documented, not silent.
EXCLUDED = {
    # AWFY macro benchmarks and Wren-suite ports: not yet tuned into CONFIG
    # (REPS/warm-up calibration, checksum cross-check against the other two
    # backends) — kept in core/ for a later pass, per benchmarks/README.md.
    "cd": "not yet tuned into CONFIG, kept for a later pass",
    "deltablue": "not yet tuned into CONFIG, kept for a later pass",
    "earley": "not yet tuned into CONFIG, kept for a later pass",
    "havlak": "not yet tuned into CONFIG, kept for a later pass",
    "for_in": "not yet tuned into CONFIG, kept for a later pass",
    "instantiation": "not yet tuned into CONFIG, kept for a later pass",
    "string_interning": "not yet tuned into CONFIG, kept for a later pass",
    "zoo": "not yet tuned into CONFIG, kept for a later pass",
}

# Regex -> replacement, applied to the core before the footer is appended.
# Used only to bring one batch into the target time window.
SIZE_PATCHES = {
    "fib":          [(r"return fibonacci\(35\)", "return fibonacci(28)")],
    "mandelbrot":   [(r"this\.mandelbrot\(750\)", "this.mandelbrot(120)")],
    "nbody":        [(r"var steps = 250000;", "var steps = 12000;")],
    "binary_trees": [(r"var maxDepth = 14;", "var maxDepth = 10;")],
}

FOOTER = """
// --- benchmark harness (generated by benchmarks/generate.py) ---
fun _batch(b, reps) {{
  var i = 0;
  var r = nil;
  while (i < reps) {{
    r = b.benchmark();
    i = i + 1;
  }}
  return r;
}}

var _b = {cls}();
var _warm = {warm};
var _meas = {meas};
var _reps = {reps};

var _k = 0;
while (_k < _warm) {{
  _batch(_b, _reps);
  _k = _k + 1;
}}

_k = 0;
while (_k < _meas) {{
  var _t0 = clock();
  var _cs = _batch(_b, _reps);
  var _us = (clock() - _t0) * 1000000.0;
  print "HARNESS " + str(_k) + " " + str(_us) + " " + str(_cs);
  _k = _k + 1;
}}
"""


PROF = HERE / "programs" / "prof"

# A core file has the harness shape if it defines a benchmark() method; files
# without it (Wren-suite ports, unused AWFY macros) are not runnable by the
# footer regardless of CONFIG/EXCLUDED.
HARNESS_SHAPE_RE = re.compile(r"\bbenchmark\s*\(\s*\)\s*{")


def check_coverage() -> None:
    known = set(CONFIG) | set(EXCLUDED)
    unaccounted = []
    for path in sorted(CORE.glob("*.lox")):
        if path.stem in known:
            continue
        if HARNESS_SHAPE_RE.search(path.read_text()):
            unaccounted.append(path.stem)
    if unaccounted:
        raise SystemExit(
            f"core/*.lox has the benchmark() shape but is in neither CONFIG "
            f"nor EXCLUDED: {unaccounted}. Add it to one of them."
        )


def main() -> None:
    check_coverage()
    OUT.mkdir(exist_ok=True)
    PROF.mkdir(parents=True, exist_ok=True)
    for name, (cls, warm, meas, reps) in CONFIG.items():
        src = (CORE / f"{name}.lox").read_text()
        for pat, repl in SIZE_PATCHES.get(name, []):
            src, n = re.subn(pat, repl, src)
            if n != 1:
                raise SystemExit(
                    f"{name}: size patch {pat!r} matched {n} times, want 1"
                )
        src = src.rstrip()
        footer = FOOTER.format(cls=cls, warm=warm, meas=meas, reps=reps)
        (OUT / f"{name}.lox").write_text(src + "\n" + footer)
        # profiling variant: one un-timed batch, no warm-up. Opcode ratios and
        # GC behaviour are the same shape as the timed run; the profiler build
        # is ~10x slower, so keep the workload to a single batch.
        prof_footer = FOOTER.format(cls=cls, warm=0, meas=1, reps=reps)
        (PROF / f"{name}.lox").write_text(src + "\n" + prof_footer)
    print(f"generated {len(CONFIG)} programs into {OUT} (+ prof/)")


if __name__ == "__main__":
    main()
